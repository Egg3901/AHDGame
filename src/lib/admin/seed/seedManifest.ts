/**
 * Seed manifest — source of truth for which MongoDB collections are seeded,
 * wiped, or preserved by reset/bootstrap.
 *
 * Consumed by:
 *   - `resetGameWorld` (which collections to wipe on a reset)
 *   - `bootstrapGameWorld` (which collections to seed on a fresh start)
 *   - Admin seeder UI (`UniversalSeeder`) and `/api/admin/seed`
 *   - CLI scripts (`scripts/reset-and-bootstrap.ts`, `scripts/bootstrap-full.ts`)
 *   - Contract tests (`bootstrapGameWorld.contract.test.ts`)
 *
 * Companion doc: `docs/reset-and-seed-contract.md`.
 *
 * If you add a new MongoDB collection, add it here so reset/bootstrap behaviour
 * stays explicit. An unclassified collection is a latent bug — it will quietly
 * survive resets and quietly miss out on bootstrap.
 */

/**
 * Lifecycle category for a MongoDB collection.
 *
 * - `reference`: Seeded on every fresh start. Drives game-world structure
 *   (states, parties, baselines, legislation types, …). Idempotent seeders
 *   re-upsert these.
 *
 * - `runtime`: Wiped on a soft world reset (`deleteProfiles: false`) and on
 *   a full reset. Regenerated by gameplay (turns, actions, elections, …).
 *   Bootstrap may pre-populate some of these to a starting state (e.g. seed
 *   elections), but their steady-state owner is gameplay, not the seeder.
 *
 * - `preserved`: Survives reset by default. Player accounts, admin metadata,
 *   community content, audit trails, migration registry. A *full* reset
 *   (`deleteProfiles: true`) may still nuke some of these (e.g. non-admin
 *   users), but the default is "keep".
 *
 * - `migration-only`: Touched only by one-off live-data migrations
 *   (`scripts/migrations/`). Never required to exist for a brand-new game.
 *
 * - `incident-only`: Touched only by incident-response scripts
 *   (`scripts/heal-*`, etc.). Never part of the normal bootstrap or reset
 *   path.
 */
