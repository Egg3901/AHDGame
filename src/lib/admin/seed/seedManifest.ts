// ─── The manifest ────────────────────────────────────────────────────────────

export const SEED_MANIFEST: ReadonlyArray<CollectionEntry> = [
  ...REFERENCE,
  ...RUNTIME,
  ...PRESERVED,
];

const BY_NAME: ReadonlyMap<string, CollectionEntry> = new Map(
  SEED_MANIFEST.map((entry) => [entry.name, entry])
);

/** Returns every collection in the given category. */
export function getCollectionsByCategory(category: CollectionCategory): CollectionEntry[] {
  return SEED_MANIFEST.filter((entry) => entry.category === category);
}

/** Returns the classification for a collection name, or undefined if unknown. */
export function getCollectionCategory(name: string): CollectionCategory | undefined {
  return BY_NAME.get(name)?.category;
}

/** Names of every runtime collection — the set wiped on reset. */
export function getRuntimeCollectionNames(): string[] {
  return getCollectionsByCategory("runtime").map((entry) => entry.name);
}

/** Names of every reference collection — the set seeded on bootstrap. */
export function getReferenceCollectionNames(): string[] {
  return getCollectionsByCategory("reference").map((entry) => entry.name);
}

/** Names of every preserved collection — the set that survives reset. */
export function getPreservedCollectionNames(): string[] {
  return getCollectionsByCategory("preserved").map((entry) => entry.name);
}

/**
 * Returns collection names present in the live database that are NOT in the
 * manifest. Use this in contract tests / admin diagnostics to surface drift.
 */
export function findUnclassifiedCollections(liveCollectionNames: ReadonlyArray<string>): string[] {
  return liveCollectionNames.filter((name) => !BY_NAME.has(name));
}
