import { describe, it, expect, vi, beforeEach } from "vitest";

vi.mock("@/lib/wiki/autoGeneratedPages", () => ({
  getAutoGeneratedWikiPagesForDisplay: vi.fn(),
}));
vi.mock("@/lib/wiki/learningPaths", () => ({
  getVisibleLearningPaths: vi.fn(),
}));

beforeEach(async () => {
  const { getAutoGeneratedWikiPagesForDisplay } = await import("@/lib/wiki/autoGeneratedPages");
  vi.mocked(getAutoGeneratedWikiPagesForDisplay).mockResolvedValue([]);
  const { getVisibleLearningPaths } = await import("@/lib/wiki/learningPaths");
  vi.mocked(getVisibleLearningPaths).mockResolvedValue([]);
});

describe("getNonPageWikiSearchCandidates", () => {
  it("includes auto-generated surfaces with their own href and kind", async () => {
    const { getAutoGeneratedWikiPagesForDisplay } = await import("@/lib/wiki/autoGeneratedPages");
    vi.mocked(getAutoGeneratedWikiPagesForDisplay).mockResolvedValue([
      {
        slug: "labour-party",
        title: "Labour Party",
        description: "A political party.",
        href: "/wiki/party/abc123",
        kind: "party",
      },
    ]);

    const { getNonPageWikiSearchCandidates } = await import("./wikiSearchSources");
    const candidates = await getNonPageWikiSearchCandidates();
    const party = candidates.find((c) => c.title === "Labour Party");

    expect(party).toBeDefined();
    expect(party!.href).toBe("/wiki/party/abc123");
    expect(party!.kind).toBe("party");
  });

  it("includes wiki categories linked by slug so the category route resolves them", async () => {
    const { getNonPageWikiSearchCandidates } = await import("./wikiSearchSources");
    const { WIKI_CATEGORIES } = await import("@/lib/wiki/categories");
    const candidates = await getNonPageWikiSearchCandidates();

    const first = WIKI_CATEGORIES[0];
    const hit = candidates.find((c) => c.kind === "category" && c.slug === first.slug);

    expect(hit).toBeDefined();
    expect(hit!.title).toBe(first.name);
    expect(hit!.href).toBe(`/wiki/category/${first.slug}`);
  });

  it("includes every wiki category", async () => {
    const { getNonPageWikiSearchCandidates } = await import("./wikiSearchSources");
    const { WIKI_CATEGORIES } = await import("@/lib/wiki/categories");
    const candidates = await getNonPageWikiSearchCandidates();

    expect(candidates.filter((c) => c.kind === "category")).toHaveLength(WIKI_CATEGORIES.length);
  });

  it("includes visible learning paths", async () => {
    const { getVisibleLearningPaths } = await import("@/lib/wiki/learningPaths");
    vi.mocked(getVisibleLearningPaths).mockResolvedValue([
      {
        id: "first-term",
        slug: "first-term",
        title: "Your First Term",
        description: "Run for office and win.",
        difficulty: "beginner",
        icon: "🎓",
        estimatedTime: "20 min",
        pages: [],
      },
    ]);

    const { getNonPageWikiSearchCandidates } = await import("./wikiSearchSources");
    const candidates = await getNonPageWikiSearchCandidates();
    const path = candidates.find((c) => c.kind === "path");

    expect(path).toBeDefined();
    expect(path!.title).toBe("Your First Term");
    expect(path!.href).toBe("/wiki/paths/first-term");
  });

  it("never returns a candidate without an href", async () => {
    const { getAutoGeneratedWikiPagesForDisplay } = await import("@/lib/wiki/autoGeneratedPages");
    vi.mocked(getAutoGeneratedWikiPagesForDisplay).mockResolvedValue([
      { slug: "s", title: "Senate Seat", description: "", href: "/wiki/seat/s", kind: "seat" },
    ]);

    const { getNonPageWikiSearchCandidates } = await import("./wikiSearchSources");
    const candidates = await getNonPageWikiSearchCandidates();

    expect(candidates.length).toBeGreaterThan(0);
    for (const c of candidates) {
      expect(c.href).toBeTruthy();
    }
  });
});
