import type { WikiPage } from "@/lib/db/types";
import { PLAYER_SUBMITTABLE_CATEGORY_IDS, getCategoryById } from "@/lib/wiki/categories";

const DEFAULT_WIKI_CATEGORY = "reference";
const PLAYER_SUBMITTABLE_CATEGORY_SET = new Set<string>(PLAYER_SUBMITTABLE_CATEGORY_IDS);

const CLAIM_MANAGED_SLUG_PATTERNS = [/^player-\d+$/, /^corp-\d+$/, /^party-[a-z]{2}-\d+$/];

export function resolveWikiCategory(tags: string[] | undefined, legacyCategory?: string): string {
  if (legacyCategory) {
    return legacyCategory;
  }

  const tagCategory = tags?.find((tag) => getCategoryById(tag));
  return tagCategory ?? legacyCategory ?? DEFAULT_WIKI_CATEGORY;
}

export function isClaimManagedWikiSlug(slug: string): boolean {
  return CLAIM_MANAGED_SLUG_PATTERNS.some((pattern) => pattern.test(slug));
}

export function isCustomWikiPage(
  page: Pick<
    WikiPage,
    | "slug"
    | "isAutoGenerated"
    | "gameIteration"
    | "gameStartDate"
    | "category"
    | "submittedBy"
    | "reviewedBy"
    | "editHistory"
  >
): boolean {
  if (page.isAutoGenerated || isClaimManagedWikiSlug(page.slug)) {
    return false;
  }

  const hasGameProvenance = Boolean(page.gameIteration || page.gameStartDate);
  if (hasGameProvenance) {
    return true;
  }

  const hasPlayerSubmissionSignals =
    Boolean(page.submittedBy) &&
    Boolean(page.reviewedBy) &&
    Boolean(page.category && PLAYER_SUBMITTABLE_CATEGORY_SET.has(page.category)) &&
    !page.editHistory?.[0]?.note?.startsWith("Reseed");

  return hasPlayerSubmissionSignals;
}
