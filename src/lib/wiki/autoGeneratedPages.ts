export type AutoGeneratedPageKind =
  "election" | "office" | "cabinet" | "leadership" | "seat" | "party";

export interface AutoGeneratedWikiPageSummary {
  slug: string;
  title: string;
  description: string;
  href: string;
  kind: AutoGeneratedPageKind;
  /**
   * Optional recency signal for sorting. Elections set this to `endTime` (or
   * `startTime` when the result hasn't resolved yet). Office/seat/party pages
   * are static and leave this undefined; the consumer should fall back to
   * alphabetical for those.
   */
  sortDate?: Date;
}

export type GeneratedOfficeKind = "executive" | "cabinet" | "leadership";

export interface GeneratedOfficeDefinition {
  slug: string;
  aliases?: string[];
  title: string;
  description: string;
  countryId: CountryId;
  kind: GeneratedOfficeKind;
  officeType?: string;
  positionId?: string;
  leadershipRole?: CongressLeader["role"];
  chamber?: "house" | "senate";
  actionBonus?: number;
  termYears?: number;
}

export interface OfficeTenureEntry {
  name: string;
  party?: string;
  partyLabel?: string;
  /** Iteration this tenure belongs to (auto entries resolve to current when unstamped). */
  iteration?: GameIteration;
  /** Rendered in-game tenure, "Week N, YYYY". */
  startWeekYear?: string;
  /** Rendered end tenure, or null ⇒ "Incumbent". */
  endWeekYear?: string | null;
  // Numeric sort keys (not rendered) used to order entries within an iteration.
  startYear?: number;
  startWeek?: number;
  order?: number;
  startDate?: Date;
  endDate?: Date;
  startTurn?: number;
  endTurn?: number;
  profileHref?: string | null;
  source:
    "country-history" | "elected-official" | "cabinet" | "nomination" | "leadership" | "manual";
  isManual?: boolean;
  /** `manualOfficeHistory` document id, for admin edit/delete of curated rows. */
  manualId?: string;
  /** Raw editable fields for manual rows, used to pre-fill the admin edit form. */
  manualData?: {
    startWeek?: number;
    startYear?: number;
    endWeek?: number;
    endYear?: number;
    /** Real-world dates as "YYYY-MM-DD" for date inputs. */
    startDate?: string;
    endDate?: string;
    isIncumbent?: boolean;
  };
  isCurrent?: boolean;
}

export interface OfficeTenureGroup {
  iteration: GameIteration;
  label: string;
  entries: OfficeTenureEntry[];
}

