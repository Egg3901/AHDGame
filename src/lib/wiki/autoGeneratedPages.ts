interface IterationContext {
  current: GameIteration;
  startingYear: number;
  anchor: GameDateAnchor;
}

/** Resolve an auto record's iteration + its preset starting year, defaulting to current. */
function resolveEntryIteration(
  record: { iteration?: GameIteration; iterationStartingYear?: number },
  ctx: IterationContext
): { iteration: GameIteration; startingYear: number } {
  return {
    iteration: record.iteration ?? ctx.current,
    startingYear: record.iterationStartingYear ?? ctx.startingYear,
  };
}

/**
 * Stamp an entry with its iteration + Week/Year + numeric sort keys. `endTurn`
 * is only honored when the end falls in the same iteration (turns reset each
 * iteration, so a cross-boundary end would render backwards); otherwise the
 * entry is treated as open ("Incumbent").
 */
function finalizeEntry(
  entry: OfficeTenureEntry,
  turn: number,
  iteration: GameIteration,
  startingYear: number,
  endTurn: number | null
): void {
  entry.iteration = iteration;
  entry.startWeekYear = weekYearFromTurn(turn, startingYear);
  entry.startYear = startingYear + Math.floor((turn - 1) / 48);
  entry.startWeek = ((turn - 1) % 48) + 1;
  entry.endWeekYear = endTurn != null ? weekYearFromTurn(endTurn, startingYear) : null;
}

/**
 * Confirmation turn for a cabinet/leadership record: the stamped `confirmedTurn`
 * (set at freeze time, correct across iterations) or, for not-yet-frozen
 * current-run records, derived from the timestamp via the current anchor.
 */
function confirmationTurn(
  record: { confirmedTurn?: number },
  timestamp: Date | undefined,
  ctx: IterationContext
): number {
  if (typeof record.confirmedTurn === "number") return record.confirmedTurn;
  return timestamp ? realDateToTurn(timestamp, ctx.anchor) : ctx.anchor.currentTurn;
}

/**
 * Finalize a live-incumbent entry (no recorded turn): place it in the current
 * iteration with a Week/Year derived from its start date and an open end.
 */
function finalizeCurrentEntry(entry: OfficeTenureEntry, ctx: IterationContext): void {
  const turn = entry.startDate
    ? realDateToTurn(entry.startDate, ctx.anchor)
    : ctx.anchor.currentTurn;
  finalizeEntry(entry, turn, ctx.current, ctx.startingYear, null);
}

/**
 * Group tenure entries by iteration. Every registry iteration (∪ the current
 * one) gets a group — even if empty — ordered Alpha < Beta < Iteration then by
 * number ascending (oldest first). Entries within a group are ordered
 * oldest→newest by (year, week, order).
 */
export function buildTenureGroups(
  entries: OfficeTenureEntry[],
  registry: GameIteration[],
  currentIteration: GameIteration
): OfficeTenureGroup[] {
  const referenced = entries
    .map((e) => e.iteration)
    .filter((it): it is GameIteration => Boolean(it));
  const ordered = orderIterations([...registry, currentIteration], referenced);
  const byKey = new Map<string, OfficeTenureEntry[]>();
  for (const e of entries) {
    if (!e.iteration) continue;
    const key = iterationKey(e.iteration);
    const list = byKey.get(key) ?? [];
    list.push(e);
    byKey.set(key, list);
  }
  return ordered.map((it) => {
    const list = (byKey.get(iterationKey(it)) ?? [])
      .slice()
      .sort(
        (a, b) =>
          (a.startYear ?? 0) - (b.startYear ?? 0) ||
          (a.startWeek ?? 0) - (b.startWeek ?? 0) ||
          (a.order ?? 0) - (b.order ?? 0)
      );
    return { iteration: it, label: iterationLabel(it), entries: list };
  });
}

async function getExecutiveHistory(
  db: Db,
  definition: GeneratedOfficeDefinition,
  ctx: IterationContext
): Promise<OfficeTenureEntry[]> {
  if (!definition.officeType) return [];
  const currentOfficial = await db
    .collection<ElectedOfficial>("electedOfficials")
    .findOne(officialFilter(definition.countryId, definition.officeType));
  const current = currentOfficialToTenure(currentOfficial);
  if (current) finalizeCurrentEntry(current, ctx);

  const events = await db
    .collection<CountryHistoryEvent>("countryHistory")
    .find({
      countryId: definition.countryId,
      eventType: "leader_change",
      officeType: definition.officeType,
    })
    .sort({ timestamp: 1 })
    .toArray();

  const history = events.map((event, index): OfficeTenureEntry => {
    const next = events[index + 1];
    const characterId = event.characterId?.toString();
    const nppId = typeof event.details?.nppId === "string" ? event.details.nppId : null;
    const { iteration, startingYear } = resolveEntryIteration(event, ctx);
    const sameIterationNext =
      next && iterationKey(resolveEntryIteration(next, ctx).iteration) === iterationKey(iteration);
    const entry: OfficeTenureEntry = {
      name: event.characterName ?? "Unknown",
      party: event.party,
      startDate: event.timestamp,
      endDate: next?.timestamp,
      startTurn: event.turn,
      endTurn: next?.turn,
      profileHref: characterId
        ? buildCharacterHref({ _id: characterId })
        : nppId
          ? buildNppHref({ _id: nppId })
          : null,
      source: "country-history",
      isCurrent: index === events.length - 1,
    };
    finalizeEntry(
      entry,
      event.turn,
      iteration,
      startingYear,
      sameIterationNext ? (next!.turn ?? null) : null
    );
    return entry;
  });

  if (history.length === 0 && current) return [current];
  if (current && history.length > 0) {
    const latest = history[history.length - 1];
    if (latest.name !== current.name) {
      history.push(current);
    }
  }
  return history;
}

async function getCabinetHistory(
  db: Db,
  definition: GeneratedOfficeDefinition,
  ctx: IterationContext
): Promise<OfficeTenureEntry[]> {
  if (!definition.positionId) return [];
  const [currentMember, nominations] = await Promise.all([
    db.collection<UnifiedCabinetMember>("cabinetMembers").findOne({
      countryId: definition.countryId,
      positionId: definition.positionId,
    }),
    db
      .collection<CabinetNomination>("cabinetNominations")
      .find({
        countryId: definition.countryId,
        positionId: definition.positionId,
        status: "confirmed",
      })
      .sort({ confirmedAt: 1, updatedAt: 1 })
      .toArray(),
  ]);

  const history = nominations.map((nomination, index): OfficeTenureEntry => {
    const next = nominations[index + 1];
    const start = nomination.confirmedAt ?? nomination.updatedAt ?? nomination.createdAt;
    const end = next ? (next.confirmedAt ?? next.updatedAt ?? next.createdAt) : undefined;
    const entry: OfficeTenureEntry = {
      name: nomination.nomineeCharacterName,
      party: nomination.nomineeParty,
      startDate: start,
      endDate: end,
      profileHref: nomination.nomineeCharacterId
        ? buildCharacterHref({ _id: nomination.nomineeCharacterId })
        : null,
      source: "nomination",
      isCurrent: index === nominations.length - 1,
    };
    const { iteration, startingYear } = resolveEntryIteration(nomination, ctx);
    const turn = confirmationTurn(nomination, start, ctx);
    const nextResolved = next ? resolveEntryIteration(next, ctx) : null;
    const sameIterationNext =
      nextResolved && iterationKey(nextResolved.iteration) === iterationKey(iteration);
    const endTurn = sameIterationNext
      ? confirmationTurn(next!, next!.confirmedAt ?? next!.updatedAt ?? next!.createdAt, ctx)
      : null;
    finalizeEntry(entry, turn, iteration, startingYear, endTurn);
    return entry;
  });

  const current = cabinetMemberToTenure(currentMember);
  if (current) finalizeCurrentEntry(current, ctx);
  if (history.length === 0 && current) return [current];
  if (current && history.length > 0) {
    const latest = history[history.length - 1];
    if (latest.name !== current.name) {
      history.push(current);
    }
  }
  return history;
}

