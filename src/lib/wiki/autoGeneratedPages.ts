function slugify(value: string): string {
  return value
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function titleWithCountry(title: string, countryId: CountryId): string {
  const config = COUNTRY_CONFIGS[countryId];
  const country = config?.executiveRealmPhrase ?? config?.name ?? countryId;
  return `${title} of ${country}`;
}

function officeSlug(title: string, countryId: CountryId): string {
  const fullTitle = titleWithCountry(title, countryId);
  return slugify(fullTitle);
}

export async function getGeneratedOfficeDefinitions(): Promise<GeneratedOfficeDefinition[]> {
  const officeCountries = await getOfficeCountries();
  const definitions: GeneratedOfficeDefinition[] = [];

  for (const countryId of officeCountries) {
    const config = COUNTRY_CONFIGS[countryId];
    const executiveKey = getExecutiveOfficeKey(countryId);
    const executive = config.officeTypes.find((office) => office.key === executiveKey);
    const executiveTitle = executive?.label ?? config.executiveTitle;
    const executiveSlug = officeSlug(executiveTitle, countryId);
    const legacyExecutiveSlug = slugify(`${executiveTitle} of ${config.name}`);

    definitions.push({
      slug: executiveSlug,
      aliases: legacyExecutiveSlug !== executiveSlug ? [legacyExecutiveSlug] : undefined,
      title: titleWithCountry(executiveTitle, countryId),
      description: `${config.executiveTitle} office history for ${config.name}, including current holder and recorded transitions.`,
      countryId,
      kind: "executive",
      officeType: executiveKey,
      actionBonus: executive?.actionBonus,
      termYears: executive?.termYears,
    });

    if (countryId === COUNTRY_CONFIGS.US.id) {
      const vicePresident = config.officeTypes.find((office) => office.key === "vicePresident");
      definitions.push({
        slug: "vice-president-of-the-united-states",
        title: "Vice President of the United States",
        description:
          "Vice presidential office history, running mate succession, and current holder.",
        countryId,
        kind: "executive",
        officeType: "vicePresident",
        actionBonus: vicePresident?.actionBonus,
        termYears: vicePresident?.termYears,
      });
    }

    for (const position of getCabinetPositions(countryId)) {
      const slug =
        countryId === COUNTRY_CONFIGS.US.id
          ? slugify(`united-states-${position.name}`)
          : slugify(`${COUNTRY_CONFIGS[countryId].name}-${position.name}`);
      definitions.push({
        slug,
        title: `${position.name}, ${COUNTRY_CONFIGS[countryId].name}`,
        description:
          position.description ??
          `${position.name} is a cabinet-level office in ${COUNTRY_CONFIGS[countryId].name}.`,
        countryId,
        kind: "cabinet",
        positionId: position.id,
      });
    }
  }

  for (const role of LEADERSHIP_ROLES) {
    const chamberPrefix = role.chamber === "house" ? "House" : "Senate";
    definitions.push({
      slug: LEADERSHIP_SLUGS[role.role] ?? slugify(`${chamberPrefix} ${role.label}`),
      title:
        role.role === "speaker_of_the_house"
          ? "Speaker of the House"
          : `${chamberPrefix} ${role.label}`,
      description: `${chamberPrefix} leadership office history in the United States Congress.`,
      countryId: "US",
      kind: "leadership",
      leadershipRole: role.role,
      chamber: role.chamber,
    });
  }

  return definitions;
}

export async function getGeneratedOfficeDefinition(
  slug: string
): Promise<GeneratedOfficeDefinition | null> {
  return (
    (await getGeneratedOfficeDefinitions()).find(
      (definition) => definition.slug === slug || definition.aliases?.includes(slug)
    ) ?? null
  );
}

export async function getGeneratedOfficeDefinitionForOffice(
  countryId: CountryId | undefined,
  officeType: string | undefined
): Promise<GeneratedOfficeDefinition | null> {
  if (!officeType) return null;
  const resolvedCountryId = countryId ?? COUNTRY_CONFIGS.US.id;
  return (
    (await getGeneratedOfficeDefinitions()).find(
      (definition) =>
        definition.kind === "executive" &&
        definition.countryId === resolvedCountryId &&
        definition.officeType === officeType
    ) ?? null
  );
}

export async function getGeneratedOfficeHrefForOffice(
  countryId: CountryId | undefined,
  officeType: string | undefined
): Promise<string | null> {
  const definition = await getGeneratedOfficeDefinitionForOffice(countryId, officeType);
  return definition ? `/wiki/${definition.slug}` : null;
}

