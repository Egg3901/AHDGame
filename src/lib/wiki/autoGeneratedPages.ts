export async function getElectionPageSummaries(): Promise<AutoGeneratedWikiPageSummary[]> {
  const db = await getDb();
  const enabledCountries = await getOfficeCountries();
  const [elections, states] = await Promise.all([
    db
      .collection<Election>("elections")
      .find(
        {
          status: { $in: ["completed", "resolved"] },
          countryId: { $in: enabledCountries },
        },
        {
          projection: {
            electionType: 1,
            electionYear: 1,
            state: 1,
            countryId: 1,
            startTime: 1,
            endTime: 1,
            cycle: 1,
          },
        }
      )
      .sort({ endTime: -1, cycle: -1 })
      .toArray(),
    db
      .collection<State>("states")
      .find({}, { projection: { name: 1 } })
      .toArray(),
  ]);
  const stateMap = new Map(states.map((state) => [state._id, state]));
  return elections.map((election) => electionSummary(election, stateMap));
}

async function getSeatPageSummaries(db: Db): Promise<AutoGeneratedWikiPageSummary[]> {
  const [seatSlugs, states] = await Promise.all([
    getAllSeatSlugs(),
    db.collection<State>("states").find({}).project({ _id: 1, name: 1 }).toArray(),
  ]);
  const stateMap = new Map(states.map((state) => [state._id, state.name]));
  return seatSlugs.map((seat) => {
    const stateName = stateMap.get(seat.stateId) ?? seat.stateId;
    const title =
      seat.type === "governor"
        ? `${stateName} Governor`
        : seat.type === "senate"
          ? `${stateName} Senate Class ${seat.senateClass ?? "?"}`
          : `${stateName} House Delegation`;
    return {
      slug: `seat-${seat.slug}`,
      title,
      description: `Generated seat page for ${title}.`,
      href: `/wiki/seat/${seat.slug}`,
      kind: "seat" as const,
    };
  });
}

async function getPartyPageSummaries(db: Db): Promise<AutoGeneratedWikiPageSummary[]> {
  const enabledCountries = await getOfficeCountries();
  const [partySlugs, parties] = await Promise.all([
    getAllPartySlugs(),
    db
      .collection<PoliticalParty>("politicalParties")
      .find({ countryId: { $in: enabledCountries } })
      .project({ countryId: 1, sequentialId: 1, name: 1, abbreviation: 1 })
      .toArray(),
  ]);
  const partyMap = new Map(
    parties.map((party) => [`${party.countryId ?? "US"}:${party.sequentialId}`, party])
  );
  // Filter party slugs to only those in enabled countries
  const enabledSet = new Set(enabledCountries);
  return partySlugs
    .filter((party) => enabledSet.has(party.countryId))
    .map((party) => {
      const record = partyMap.get(`${party.countryId}:${party.id}`);
      const title = record?.name ?? `Party ${party.id}`;
      return {
        slug: `party-${party.countryId.toLowerCase()}-${party.id}`,
        title,
        description: `Generated political party page for ${title}.`,
        href: `/wiki/party/${party.id}?country=${party.countryId.toLowerCase()}`,
        kind: "party" as const,
      };
    });
}

