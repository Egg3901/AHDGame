async function getLeadershipNominations(
  db: Db,
  role: CongressLeader["role"]
): Promise<NominationWithSharedFields[]> {
  if (role === "speaker_of_the_house") {
    return db
      .collection<SpeakerNomination>("speakerNominations")
      .find({ status: "confirmed" })
      .sort({ updatedAt: 1 })
      .toArray();
  }

  const houseRole =
    role === "majority_leader_house"
      ? "majority_leader"
      : role === "minority_leader_house"
        ? "minority_leader"
        : null;
  if (houseRole) {
    return db
      .collection<HouseLeadershipNomination>("houseLeadershipNominations")
      .find({ role: houseRole, status: "confirmed" })
      .sort({ updatedAt: 1 })
      .toArray();
  }

  const senateRole =
    role === "president_pro_tempore"
      ? "pro_tempore"
      : role === "majority_leader_senate"
        ? "majority_leader"
        : role === "minority_leader_senate"
          ? "minority_leader"
          : null;
  if (senateRole) {
    return db
      .collection<SenateLeadershipNomination>("senateLeadershipNominations")
      .find({ role: senateRole, status: "confirmed" })
      .sort({ updatedAt: 1 })
      .toArray();
  }

  return [];
}

async function getLeadershipHistory(
  db: Db,
  definition: GeneratedOfficeDefinition,
  ctx: IterationContext
): Promise<OfficeTenureEntry[]> {
  if (!definition.leadershipRole) return [];
  const [currentLeader, nominations] = await Promise.all([
    db.collection<CongressLeader>("congressLeaders").findOne({ role: definition.leadershipRole }),
    getLeadershipNominations(db, definition.leadershipRole),
  ]);

  const history = nominations.map((nomination, index): OfficeTenureEntry => {
    const next = nominations[index + 1];
    const start = nomination.updatedAt ?? nomination.createdAt;
    const entry: OfficeTenureEntry = {
      name: nomination.nomineeName,
      party: nomination.nomineeParty,
      startDate: start,
      endDate: next ? (next.updatedAt ?? next.createdAt) : undefined,
      profileHref: nomination.nomineeId ? buildCharacterHref({ _id: nomination.nomineeId }) : null,
      source: "leadership",
      isCurrent: index === nominations.length - 1,
    };
    const { iteration, startingYear } = resolveEntryIteration(nomination, ctx);
    const turn = confirmationTurn(nomination, start, ctx);
    const nextResolved = next ? resolveEntryIteration(next, ctx) : null;
    const sameIterationNext =
      nextResolved && iterationKey(nextResolved.iteration) === iterationKey(iteration);
    const endTurn = sameIterationNext
      ? confirmationTurn(next!, next!.updatedAt ?? next!.createdAt, ctx)
      : null;
    finalizeEntry(entry, turn, iteration, startingYear, endTurn);
    return entry;
  });

  const current = leadershipToTenure(currentLeader);
  if (current) finalizeCurrentEntry(current, ctx);
  if (history.length === 0 && current) return [current];
  if (current && history.length > 0) {
    const latest = history[history.length - 1];
    if (latest.name !== current.name) {
      history.push(current);
    }
  }
  return history;
}

export function generatedOfficeDefaultContent(definition: GeneratedOfficeDefinition): string {
  const country = COUNTRY_CONFIGS[definition.countryId];
  const termText =
    definition.termYears != null
      ? ` The standard term length is ${definition.termYears} game year${definition.termYears === 1 ? "" : "s"}.`
      : "";
  const actionText =
    definition.actionBonus != null
      ? ` The office grants a +${definition.actionBonus} action bonus while held.`
      : "";

  if (definition.kind === "cabinet") {
    return `${definition.description}\n\nIn *A House Divided*, this cabinet office is part of ${country.name}'s executive administration. The office page is generated from live appointment records, so the holder table updates as confirmations and appointments happen. Editors can add narrative context by creating a wiki page with this slug; the generated holder history remains attached below the article text.`;
  }

  if (definition.kind === "leadership") {
    return `${definition.description}\n\nThis page tracks the office as a living institutional record. The holder table is generated from congressional leadership records and confirmed leadership nominations where available, preserving a running list of speakers, floor leaders, whips, and Senate officers as the simulation develops.`;
  }

  return `${definition.title} is the senior executive office of ${country.name}.${termText}${actionText}\n\nThis generated article records the office's incumbent and known tenure history. Leader transitions are pulled from country history events where available, with current office records used as a fallback until a full transition history accumulates.`;
}

export async function getGeneratedOfficePageData(
  slug: string
): Promise<GeneratedOfficePageData | null> {
  const definition = await getGeneratedOfficeDefinition(slug);
  if (!definition) return null;

  // Step 5: If the office's country is not enabled, return null to prevent
  // rendering office pages for disabled countries.
  const enabledCountries = await getOfficeCountries();
  if (!enabledCountries.includes(definition.countryId)) return null;

  const db = await getDb();
  const gameState = await getGameState(db);
  const currentIteration: GameIteration = gameState?.iteration ?? { type: "Beta", number: 2 };
  const startingYear = gameState?.startingYear ?? STARTING_YEAR;
  const ctx: IterationContext = {
    current: currentIteration,
    startingYear,
    anchor: {
      currentTurn: gameState?.currentTurn ?? 1,
      lastTurnProcessed: gameState?.lastTurnProcessed ?? new Date(),
      startingYear,
    },
  };
  const registry = gameState?.iterationHistory ?? [currentIteration];

  const [editablePage, partyLabels, history, manual] = await Promise.all([
    db
      .collection<WikiPage>("wikiPages")
      .findOne({ slug, status: "published", private: { $ne: true } }, { projection: { _id: 1 } }),
    loadPartyLabels(db, definition.countryId),
    definition.kind === "cabinet"
      ? getCabinetHistory(db, definition, ctx)
      : definition.kind === "leadership"
        ? getLeadershipHistory(db, definition, ctx)
        : getExecutiveHistory(db, definition, ctx),
    loadManualOfficeHistory(db, definition),
  ]);

  const labeledHistory = applyPartyLabels(history, partyLabels);
  const currentHolder = labeledHistory.find((entry) => entry.isCurrent) ?? null;
  const labeledManual = applyPartyLabels(manual.map(manualEntryToTenure), partyLabels);
  const allEntries = [...labeledHistory, ...labeledManual];

  return {
    definition,
    currentHolder,
    tenureGroups: buildTenureGroups(allEntries, registry, currentIteration),
    hasEditableContent: Boolean(editablePage),
  };
}
