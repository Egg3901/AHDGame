function electionStateName(election: Election, states: Map<string, State>): string {
  if (election.electionType === "president") {
    return COUNTRY_CONFIGS[election.countryId ?? "US"]?.name ?? "United States";
  }
  if (election.electionType === "uachtaran") {
    return COUNTRY_CONFIGS[election.countryId ?? "IE"]?.name ?? "Ireland";
  }
  return states.get(election.state)?.name ?? election.state;
}

function electionSummary(
  election: Election,
  states: Map<string, State>
): AutoGeneratedWikiPageSummary {
  const stateName = electionStateName(election, states);
  const year = resolveElectionYear(election);
  const typeLabel = electionTypeLabel(election);
  const title = `${year} ${stateName} ${typeLabel}`;
  return {
    slug: `election-${election._id.toString()}`,
    title,
    description: `Generated election results page for ${title}.`,
    href: `/wiki/elections/${election._id.toString()}`,
    kind: "election" as const,
    sortDate: election.endTime ?? election.startTime ?? undefined,
  };
}

