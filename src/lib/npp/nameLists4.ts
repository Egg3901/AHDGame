/**
 * NPP name pools — Eastern-bloc lists: HU, PL, CS, BG, RO, YU, BLR, the BAL
 * composite (Estonia/Latvia/Lithuania), Soviet minority sub-pools for RU, and
 * the GDR-era first names for DD.
 *
 * Same conventions as nameLists1-3: pools are ASCII-only (diacritics are
 * dropped the way English-language sources drop them — "Wojcik" not "Wójcik",
 * "Novak" not "Novák"), and the names read correctly for a legislator seated
 * anywhere in the 1950s-1980s window these countries are playable in.
 *
 * Real bloc-era leaders are deliberately absent as surnames where the pairing
 * would be unmistakable (no Zhivkov, Ceausescu, Gomulka, Ulbricht, Honecker,
 * Husak, Kadar, Tito/Broz, or Hoxha). Common surnames that merely happen to
 * be shared with a public figure are kept — they are common for a reason.
 *
 * The generator functions and country routing stay in nameGenerator.ts.
 */

