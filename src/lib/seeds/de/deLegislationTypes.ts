/**
 * Germany-specific legislation types — JP-parity expansion.
 *
 * PR1 (2026-05-26) added the complete 8-type tax catalogue: 7 federal taxes
 * (income, solidaritätszuschlag, VAT, domestic corp, foreign corp, payroll/
 * social insurance, customs/tariffs) plus 1 regional (Gewerbesteuer-Hebesatz).
 * Each uses 11 rate brackets via the unified `taxRateOptions` helper.
 *
 * PR2 (2026-05-27) added the 12 healthcare/education/social non-tax types
 * (de_health_insurance, de_elder_care, de_mental_health, de_public_health,
 * de_education_funding, de_university_tuition, de_academic_reform,
 * de_research_science, de_pension_system, de_family_policy,
 * de_unemployment_welfare, de_gender_equality). Each uses 7 LARP options
 * via the unified policyOptions/withPerCapitaCosts helpers with EUR/cap
 * costs calibrated against the 2020 Bundeshaushalt.
 *
 * PR3 (2026-05-27) added the 11 defense/foreign/tech/public-safety types
 * (de_bundeswehr_funding, de_defense_posture, de_cybersecurity,
 * de_eu_integration, de_foreign_aid_diplomacy, de_trade_agreements,
 * de_robotics_ai, de_digital_governance, de_policing_public_safety,
 * de_criminal_justice, de_constitutional_protection). de_bundeswehr_funding
 * uses an INVERTED cost ladder (left=low spend, right=high spend) per
 * spec §14.3 head note.
 *
 * PR4 (2026-05-27) added the 22 types completing the national non-tax
 * catalogue: 19 new types (de_fiscal_stimulus_act, de_labor_reform,
 * de_sme_mittelstand, de_rail_transport, de_digital_infrastructure,
 * de_housing, de_nuclear_energy, de_carbon_pricing, de_climate_targets,
 * de_asylum_policy, de_integration_programs, de_agricultural_subsidies,
 * de_food_security, de_animal_welfare, de_grundgesetz_reform,
 * de_electoral_reform, de_government_ethics, de_public_broadcasting,
 * de_press_freedom) + 3 legacy rewrites (de_minimum_wage,
 * de_renewable_energy_target, de_immigration_policy) expanded from
 * 4-5 to 7 options per spec §10.4. de_minimum_wage uses minimumWageRate
 * (€/hr) per option instead of annualCostPerCapita.
 *
 * PR5 (2026-05-27) added the 6 Land-level non-tax types (de_land_education,
 * de_land_police, de_land_culture, de_land_economic_development,
 * de_land_health_services, de_land_municipal_grants). All use
 * allowedScope: "state", landtagCommitteePositions, and
 * effectTarget.scope: "state". de_land_municipal_grants spending routes
 * via budgetCategory: "localGovernment" in calculateStateSpending.
 * Per-Land base-policy records generated by buildBasePolicies() — 16
 * Länder × 6 types = 96 records.
 *
 * The DE legislation overhaul (PR1-PR5) is COMPLETE: 8 federal tax types,
 * 1 regional tax type (Gewerbesteuer-Hebesatz), 45 national non-tax types
 * (12 PR2 + 11 PR3 + 22 PR4), and 6 Land-level non-tax types. See
 * `docs/plans/archive/2026-05/2026-05-26-de-legislation-overhaul-design.md`.
 *
 * Naming convention (per playerbase poll, 2026-05-26): English `name` for UI;
 * original German Gesetz name lives in `explanation` and option `description`
 * fields wrapped in parens for flavour. Political-vocabulary terms (Mittelstand,
 * Bürgerversicherung, Pflegeversicherung, Sozialstaat, etc.) stay German.
 *
 * Committee positions use the "bundestag" chamber key for federal types and
 * "landtag" (added 2026-05-26) for Land-level types. countryScope: "de" gates
 * everything to Germany only.
 *
 * Helpers: shared `policyOptions` / `taxRateOptions` from
 * `../reference/policyOptionHelpers`. No DE-specific helper.
 */

