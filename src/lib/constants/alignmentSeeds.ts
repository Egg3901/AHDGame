/**
 * Authored opening alignments per world start.
 *
 * Each row is a share array in the POLE ORDER OF THAT START — 1953 is
 * [WEST, EAST]; 1979 adds NAM; 1991 onward is
 * [WASHINGTON, MOSCOW, BEIJING, NAM]. The remainder to 100 is the nation's
 * non-aligned share and is never stored here.
 *
 * The 1953 rows are anchored to the source design's published axis values, so
 * `WEST - EAST` reproduces them exactly (DD -86, YU -28, FI -22, SE +12,
 * IT +45, TR +52, US +95). Note the scalar fixes the DIFFERENCE but not the
 * remainder, and the remainder is what encodes how much of a nation is in
 * play: Sweden and Yugoslavia both sit near neutral, but Sweden's large
 * remainder means genuinely uncommitted while Yugoslavia's split means
 * actively contested. Remainders are authored deliberately.
 *
 * Entities with no row here fall to the derive rules in
 * `src/lib/alignment/seedAlignment.ts` — metropole, decolonised, or default.
 *
 * Client-safe: no db imports.
 */

